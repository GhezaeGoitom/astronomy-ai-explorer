-- ============================================================
-- 4. PUBLICATION
-- ============================================================

CREATE TABLE publish (
                         id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         date_published DATE,
                         place          VARCHAR(100)
);


-- ============================================================
-- 5. DISCOVERY
-- ============================================================

CREATE TABLE discover (
                          id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          date_discovered DATE,
                          description     TEXT,
                          coordinate      VARCHAR(100),

                          publish_id      BIGINT,
                          discovered_by   BIGINT,

                          CONSTRAINT fk_discover_publish
                              FOREIGN KEY (publish_id)
                                  REFERENCES publish (id),

                          CONSTRAINT fk_discover_person
                              FOREIGN KEY (discovered_by)
                                  REFERENCES person (id)
);


-- ============================================================
-- 6. GALAXY
-- ============================================================

CREATE TABLE galaxy (
                        id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name             VARCHAR(100) NOT NULL,

                        universe_id      BIGINT,
                        galactic_cluster_id BIGINT,
                        description      TEXT,
                        discover_id      BIGINT,

                        CONSTRAINT uk_galaxy_name UNIQUE (name),

                        CONSTRAINT fk_galaxy_universe
                            FOREIGN KEY (universe_id)
                                REFERENCES universe (id),

                        CONSTRAINT fk_galaxy_cluster
                            FOREIGN KEY (galactic_cluster_id)
                                REFERENCES galactic_cluster (id),

                        CONSTRAINT fk_galaxy_discover
                            FOREIGN KEY (discover_id)
                                REFERENCES discover (id)
);


-- ============================================================
-- 7. SOLAR SYSTEM
-- ============================================================

CREATE TABLE solar_system (
                              id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              name         VARCHAR(100) NOT NULL,

                              galaxy_id    BIGINT,
                              description  TEXT,
                              discover_id  BIGINT,

                              CONSTRAINT uk_solar_system_name UNIQUE (name),

                              CONSTRAINT fk_solar_system_galaxy
                                  FOREIGN KEY (galaxy_id)
                                      REFERENCES galaxy (id),

                              CONSTRAINT fk_solar_system_discover
                                  FOREIGN KEY (discover_id)
                                      REFERENCES discover (id)
);


-- ============================================================
-- 8. PLANET
-- ============================================================

CREATE TABLE planet (
                        id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name          VARCHAR(100) NOT NULL,

                        object_size   BIGINT,
                        object_mass   BIGINT,
                        score         INTEGER,

                        description   TEXT,

                        solar_system_id BIGINT,
                        discover_id     BIGINT,

                        CONSTRAINT uk_planet_name UNIQUE (name),

                        CONSTRAINT fk_planet_solar_system
                            FOREIGN KEY (solar_system_id)
                                REFERENCES solar_system (id),

                        CONSTRAINT fk_planet_discover
                            FOREIGN KEY (discover_id)
                                REFERENCES discover (id)
);


-- ============================================================
-- 9. STAR
-- ============================================================

CREATE TABLE star (
                      id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      name            VARCHAR(100) NOT NULL,

                      object_size     BIGINT,
                      object_mass     BIGINT,

                      description     TEXT,

                      solar_system_id BIGINT,
                      discover_id     BIGINT,

                      CONSTRAINT uk_star_name UNIQUE (name),

                      CONSTRAINT fk_star_solar_system
                          FOREIGN KEY (solar_system_id)
                              REFERENCES solar_system (id),

                      CONSTRAINT fk_star_discover
                          FOREIGN KEY (discover_id)
                              REFERENCES discover (id)
);


-- ============================================================
-- 10. BLACK HOLE
-- ============================================================

CREATE TABLE black_hole (
                            id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            name            VARCHAR(100) NOT NULL,

                            object_size     BIGINT,
                            object_mass     BIGINT,

                            description     TEXT,

                            galaxy_id       BIGINT,
                            discover_id     BIGINT,

                            CONSTRAINT uk_black_hole_name UNIQUE (name),

                            CONSTRAINT fk_black_hole_galaxy
                                FOREIGN KEY (galaxy_id)
                                    REFERENCES galaxy (id),

                            CONSTRAINT fk_black_hole_discover
                                FOREIGN KEY (discover_id)
                                    REFERENCES discover (id)
);


-- ============================================================
-- 11. SUPERNOVA
-- ============================================================

CREATE TABLE supernova (
                           id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           name           VARCHAR(100) NOT NULL,

                           brightness     BIGINT,

                           universe_id    BIGINT,
                           discover_id    BIGINT,

                           description    TEXT,

                           CONSTRAINT uk_supernova_name UNIQUE (name),

                           CONSTRAINT fk_supernova_universe
                               FOREIGN KEY (universe_id)
                                   REFERENCES universe (id),

                           CONSTRAINT fk_supernova_discover
                               FOREIGN KEY (discover_id)
                                   REFERENCES discover (id)
);


