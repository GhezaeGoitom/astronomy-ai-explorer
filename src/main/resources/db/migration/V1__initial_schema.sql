-- ============================================================
-- 2. ASTRONOMY DOMAIN TABLES
-- ============================================================

-- ------------------------------------------------------------
-- UNIVERSE
-- ------------------------------------------------------------

CREATE TABLE universe (
                          id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          name        VARCHAR(100) NOT NULL,
                          description TEXT,
                          coordinate  VARCHAR(100),

                          CONSTRAINT uk_universe_name UNIQUE (name)
);


-- ------------------------------------------------------------
-- GALACTIC SUPERCLUSTER
-- ------------------------------------------------------------

CREATE TABLE galactic_supercluster (
                                       id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                       name        VARCHAR(100) NOT NULL,
                                       description TEXT,

                                       CONSTRAINT uk_galactic_supercluster_name UNIQUE (name)
);


-- ------------------------------------------------------------
-- GALACTIC CLUSTER
-- ------------------------------------------------------------

CREATE TABLE galactic_cluster (
                                  id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  name                   VARCHAR(100) NOT NULL,
                                  galactic_supercluster_id  BIGINT,
                                  description            TEXT,

                                  CONSTRAINT uk_galactic_cluster_name UNIQUE (name),

                                  CONSTRAINT fk_cluster_supercluster
                                      FOREIGN KEY (galactic_supercluster_id)
                                          REFERENCES galactic_supercluster (id)
);


-- ============================================================
-- 3. APPLICATION USERS / SECURITY
-- ============================================================

-- ------------------------------------------------------------
-- APP USER
--
-- Contains authentication/account information.
-- Password must contain a BCrypt/Argon2 hash, never plaintext.
-- ------------------------------------------------------------

CREATE TABLE app_user (
                          id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          username    VARCHAR(50) NOT NULL,
                          email       VARCHAR(255) NOT NULL,
                          password    VARCHAR(255) NOT NULL,
                          enabled     BOOLEAN NOT NULL DEFAULT TRUE,
                          created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          CONSTRAINT uk_app_user_username UNIQUE (username),
                          CONSTRAINT uk_app_user_email UNIQUE (email)
);


-- ------------------------------------------------------------
-- PERSON
--
-- Domain/profile information for a real person.
--
-- The ID is also the APP_USER ID.
-- This creates a one-to-one relationship:
--
-- APP_USER 1 ---- 1 PERSON
--
-- Not every application user needs to have a PERSON record.
-- For example, a guest account may only exist in APP_USER.
-- ------------------------------------------------------------

CREATE TABLE person (
                        id          BIGINT PRIMARY KEY,
                        firstname   VARCHAR(50) NOT NULL,
                        lastname    VARCHAR(50) NOT NULL,

                        CONSTRAINT fk_person_app_user
                            FOREIGN KEY (id)
                                REFERENCES app_user (id)
                                ON DELETE CASCADE
);


-- ------------------------------------------------------------
-- ROLES
-- ------------------------------------------------------------

CREATE TABLE app_role (
                          id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          name    VARCHAR(30) NOT NULL,

                          CONSTRAINT uk_app_role_name UNIQUE (name)
);


-- ------------------------------------------------------------
-- USER ↔ ROLE
--
-- A user can have multiple roles.
-- A role can belong to multiple users.
-- ------------------------------------------------------------

CREATE TABLE app_user_role (
                               user_id BIGINT NOT NULL,
                               role_id INTEGER NOT NULL,

                               PRIMARY KEY (user_id, role_id),

                               CONSTRAINT fk_user_role_user
                                   FOREIGN KEY (user_id)
                                       REFERENCES app_user (id)
                                       ON DELETE CASCADE,

                               CONSTRAINT fk_user_role_role
                                   FOREIGN KEY (role_id)
                                       REFERENCES app_role (id)
                                       ON DELETE CASCADE
);


